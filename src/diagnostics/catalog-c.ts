/** A complete program around `body`, for the tests. Line 3 is the first body line. */
const main = (body: string, before = ""): string => `#include <stdio.h>\n${before}int main() {\n${body}\n    return 0;\n}\n`;

const count = (text: string, char: string): number => text.split(char).length - 1;

/** The statement on the previous code line was never finished. */
function previousLineUnfinished(context: MatchContext): boolean {
  const line = context.parsed.line;
  if (line === null) return false;
  const previous = context.previousCodeLine(line);
  if (previous === null) return false;
  const text = context.lineText(previous).replace(/\/\/.*$/, "").trim();
  return !/[;{}:,(]$/.test(text) && !/^(else|do)\b/.test(text);
}

const previousLine = (context: MatchContext): number | null =>
  context.parsed.line === null ? null : context.previousCodeLine(context.parsed.line);

